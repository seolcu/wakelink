package app.wakelink.android.pairing

import androidx.compose.foundation.layout.Column
import androidx.compose.foundation.layout.fillMaxSize
import androidx.compose.foundation.layout.padding
import androidx.compose.material3.Button
import androidx.compose.material3.HorizontalDivider
import androidx.compose.material3.OutlinedTextField
import androidx.compose.material3.Text
import androidx.compose.runtime.Composable
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.remember
import androidx.compose.runtime.rememberCoroutineScope
import androidx.compose.runtime.setValue
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.unit.dp
import app.wakelink.android.data.TokenStore
import app.wakelink.android.network.AcceptInviteRequest
import app.wakelink.android.network.ApiClient
import kotlinx.coroutines.launch

/**
 * Mutual-consent pairing: an invite code must be deliberately generated by
 * one side and deliberately typed in by the other. Neither side can add a
 * contact unilaterally -- see server/internal/api/pairing.go.
 */
@Composable
fun PairingScreen(onDone: () -> Unit) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    val api = remember { ApiClient.create(TokenStore(context)) }

    var myCode by remember { mutableStateOf<String?>(null) }
    var enteredCode by remember { mutableStateOf("") }
    var status by remember { mutableStateOf<String?>(null) }

    Column(modifier = Modifier.fillMaxSize().padding(24.dp)) {
        Text("나를 깨울 수 있는 상대 추가하기")

        Button(
            modifier = Modifier.padding(top = 16.dp),
            onClick = {
                scope.launch {
                    status = null
                    try {
                        myCode = api.createInvite().pairingCode
                    } catch (e: Exception) {
                        status = "코드 생성 실패: ${e.message}"
                    }
                }
            },
        ) {
            Text("초대 코드 만들기")
        }
        myCode?.let {
            Text("이 코드를 상대방에게 알려주세요: $it", modifier = Modifier.padding(top = 8.dp))
        }

        HorizontalDivider(modifier = Modifier.padding(vertical = 24.dp))

        Text("상대방이 알려준 코드 입력하기")
        OutlinedTextField(
            value = enteredCode,
            onValueChange = { enteredCode = it.uppercase() },
            singleLine = true,
            modifier = Modifier.padding(top = 8.dp),
        )
        Button(
            enabled = enteredCode.isNotBlank(),
            modifier = Modifier.padding(top = 16.dp),
            onClick = {
                scope.launch {
                    status = null
                    try {
                        val res = api.acceptInvite(AcceptInviteRequest(pairingCode = enteredCode.trim()))
                        status = "${res.pairedWithName}님과 연결되었습니다"
                        onDone()
                    } catch (e: Exception) {
                        status = "연결 실패: ${e.message}"
                    }
                }
            },
        ) {
            Text("연결하기")
        }

        status?.let { Text(it, modifier = Modifier.padding(top = 16.dp)) }
    }
}
