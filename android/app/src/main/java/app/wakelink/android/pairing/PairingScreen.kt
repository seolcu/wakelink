/**
 * Mutual-consent pairing: an invite code must be deliberately generated by
 * one side and deliberately typed in by the other. Neither side can add a
 * contact unilaterally -- see server/internal/api/pairing.go. A code
 * arriving via a wakelink://invite link ([initialCode]) is only pre-filled;
 * the user still has to press "connect".
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun PairingScreen(initialCode: String?, onDone: () -> Unit) {
    val context = LocalContext.current
    val clipboard = LocalClipboardManager.current
    val scope = rememberCoroutineScope()
    val api = remember { ApiClient.create(TokenStore(context)) }

    var invite by remember { mutableStateOf<CreateInviteResponse?>(null) }
    var issuedAt by remember { mutableLongStateOf(0L) }
    var nowSeconds by remember { mutableLongStateOf(System.currentTimeMillis() / 1000) }
    var enteredCode by remember { mutableStateOf(initialCode?.let(::normalizeInviteCode) ?: "") }
    var creating by remember { mutableStateOf(false) }
    var accepting by remember { mutableStateOf(false) }
    var createError by remember { mutableStateOf<String?>(null) }
    var acceptError by remember { mutableStateOf<String?>(null) }

    LaunchedEffect(invite) {
        val expiresAt = invite?.expiresAt ?: return@LaunchedEffect
        while (true) {
            nowSeconds = System.currentTimeMillis() / 1000
            if (nowSeconds >= expiresAt) break
            delay(1_000)
        }
    }

    fun createInvite() {
        creating = true
        createError = null
        scope.launch {
            try {
                invite = api.createInvite()
                issuedAt = System.currentTimeMillis() / 1000
                nowSeconds = issuedAt
            } catch (e: Exception) {
                createError = context.getString(R.string.pairing_create_failed, e.toUserMessage(context))
            } finally {
                creating = false
            }
        }
    }

    Scaffold(
        containerColor = MaterialTheme.colorScheme.background,
        topBar = {
            TopAppBar(
                title = { Text(stringResource(R.string.pairing_title)) },
                navigationIcon = {
                    IconButton(onClick = onDone) { Icon(Icons.AutoMirrored.Rounded.ArrowBack, contentDescription = stringResource(R.string.common_back)) }
                },
                colors = TopAppBarDefaults.topAppBarColors(containerColor = MaterialTheme.colorScheme.background),
            )
        },
    ) { innerPadding ->
        Column(
            verticalArrangement = Arrangement.spacedBy(16.dp),
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
                .verticalScroll(rememberScrollState())
                .padding(start = 16.dp, end = 16.dp, bottom = 32.dp),
        ) {
            Text(
                stringResource(R.string.pairing_intro),
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                modifier = Modifier.padding(horizontal = 4.dp),
            )

            PairingSection(title = stringResource(R.string.pairing_send_section), step = "A") {
                val current = invite
                val remaining = current?.let { it.expiresAt - nowSeconds } ?: 0
                if (current != null && remaining > 0) {
                    CodeBoxes(current.pairingCode)
                    val total = (current.expiresAt - issuedAt).coerceAtLeast(1)
                    LinearProgressIndicator(
                        progress = { remaining.toFloat() / total },
                        color = MaterialTheme.colorScheme.secondary,
                        trackColor = MaterialTheme.colorScheme.surfaceVariant,
                        modifier = Modifier.fillMaxWidth().padding(top = 4.dp),
                    )
                    Text(
                        stringResource(R.string.pairing_expires_in, formatRemaining(remaining)),
                        style = MaterialTheme.typography.labelMedium,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                    Row(horizontalArrangement = Arrangement.spacedBy(8.dp), modifier = Modifier.fillMaxWidth()) {
                        Button(
                            modifier = Modifier.weight(1f),
                            onClick = {
                                val send = Intent(Intent.ACTION_SEND).apply {
                                    type = "text/plain"
                                    val link = inviteWebLink(BuildConfig.DEFAULT_SERVER_BASE_URL, current.pairingCode)
                                    putExtra(Intent.EXTRA_TEXT, context.getString(R.string.pairing_share_text, current.pairingCode, link))
                                }
                                context.startActivity(Intent.createChooser(send, context.getString(R.string.pairing_share_chooser)))
                            },
                        ) {
                            Icon(Icons.Rounded.Share, contentDescription = null, modifier = Modifier.size(18.dp))
                            Spacer(Modifier.size(8.dp))
                            Text(stringResource(R.string.pairing_share))
                        }
                        OutlinedButton(
                            modifier = Modifier.weight(1f),
                            onClick = {
                                clipboard.setText(AnnotatedString(current.pairingCode))
                                Toast.makeText(context, R.string.pairing_copied, Toast.LENGTH_SHORT).show()
                            },
                        ) {
                            Icon(Icons.Rounded.ContentCopy, contentDescription = null, modifier = Modifier.size(18.dp))
                            Spacer(Modifier.size(8.dp))
                            Text(stringResource(R.string.common_copy))
                        }
                    }
                } else {
                    Text(
                        stringResource(if (current != null) R.string.pairing_code_expired else R.string.pairing_code_rules),
                        style = MaterialTheme.typography.bodyMedium,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                    Button(enabled = !creating, onClick = ::createInvite, modifier = Modifier.fillMaxWidth().height(52.dp)) {
                        if (creating) {
                            CircularProgressIndicator(strokeWidth = 2.dp, modifier = Modifier.size(20.dp))
                        } else {
                            Text(stringResource(if (current == null) R.string.pairing_create else R.string.pairing_create_new))
                        }
                    }
                }
                createError?.let { StatusPill(StatusKind.ERROR, it, Modifier.fillMaxWidth()) }
            }

            PairingSection(title = stringResource(R.string.pairing_enter_section), step = "B") {
                if (initialCode != null) {
                    StatusPill(
                        StatusKind.INFO,
                        stringResource(R.string.pairing_link_notice),
                        Modifier.fillMaxWidth(),
                    )
                }
                OutlinedTextField(
                    value = enteredCode,
                    onValueChange = { enteredCode = normalizeInviteCode(it) },
                    singleLine = true,
                    label = { Text(stringResource(R.string.pairing_code_label)) },
                    placeholder = { Text(stringResource(R.string.pairing_code_placeholder)) },
                    leadingIcon = { Icon(Icons.Rounded.Link, contentDescription = null) },
                    textStyle = MaterialTheme.typography.titleMedium.copy(fontFamily = FontFamily.Monospace, letterSpacing = 2.sp),
                    isError = acceptError != null,
                    supportingText = acceptError?.let { { Text(it) } },
                    modifier = Modifier.fillMaxWidth(),
                )
                Button(
                    enabled = enteredCode.isNotBlank() && !accepting,
                    colors = ButtonDefaults.buttonColors(
                        containerColor = MaterialTheme.colorScheme.secondary,
                        contentColor = MaterialTheme.colorScheme.onSecondary,
                    ),
                    modifier = Modifier.fillMaxWidth().height(52.dp),
                    onClick = {
                        accepting = true
                        acceptError = null
                        scope.launch {
                            try {
                                val res = api.acceptInvite(AcceptInviteRequest(pairingCode = enteredCode))
                                Toast.makeText(context, context.getString(R.string.pairing_connected, res.pairedWithName), Toast.LENGTH_SHORT).show()
                                onDone()
                            } catch (e: Exception) {
                                acceptError = e.toUserMessage(context)
                            } finally {
                                accepting = false
                            }
                        }
                    },
                ) {
                    if (accepting) {
                        CircularProgressIndicator(strokeWidth = 2.dp, modifier = Modifier.size(20.dp))
                    } else {
                        Text(stringResource(R.string.pairing_connect))
                    }
                }
            }
        }
    }
}

/** A card for one side of the two-step exchange, labelled A (give a code) or B (enter one). */
@Composable
private fun PairingSection(title: String, step: String, content: @Composable () -> Unit) {
    Card(
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
        shape = MaterialTheme.shapes.large,
        modifier = Modifier.fillMaxWidth(),
    ) {
        Column(modifier = Modifier.padding(20.dp), verticalArrangement = Arrangement.spacedBy(12.dp)) {
            Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                Box(
                    contentAlignment = Alignment.Center,
                    modifier = Modifier
                        .size(28.dp)
                        .background(MaterialTheme.colorScheme.primaryContainer, MaterialTheme.shapes.small),
                ) {
                    Text(step, style = MaterialTheme.typography.labelLarge, color = MaterialTheme.colorScheme.onPrimaryContainer)
                }
                Text(title, style = MaterialTheme.typography.titleMedium)
            }
            content()
        }
    }
}

/** The invite code, one character per box, so it's easy to read aloud or copy by eye. */
@Composable
private fun CodeBoxes(code: String) {
    Row(horizontalArrangement = Arrangement.spacedBy(6.dp), modifier = Modifier.fillMaxWidth()) {
        code.forEach { ch ->
            Box(
                contentAlignment = Alignment.Center,
                modifier = Modifier
                    .weight(1f)
                    .aspectRatio(0.78f)
                    .background(MaterialTheme.colorScheme.surfaceVariant, MaterialTheme.shapes.small),
            ) {
                Text(
                    ch.toString(),
                    style = MaterialTheme.typography.headlineMedium.copy(fontFamily = FontFamily.Monospace, fontWeight = FontWeight.Bold),
                    color = MaterialTheme.colorScheme.onSurface,
                )
            }
        }
    }
}
